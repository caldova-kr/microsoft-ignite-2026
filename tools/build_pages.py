#!/usr/bin/env python3
"""Generate catalog views and site indexes from catalog/sessions.json + catalog/triage.yml + note frontmatter.

Outputs (all generated — never edit by hand):
  catalog/SESSIONS.md        GitHub-browsable list of every session, grouped by session type
  docs/catalog/sessions.json compact data for the site's session explorer
  docs/sessions/index.md     index of written notes
  docs/index.md              stats + recent notes blocks between <!-- gen:* --> markers

`--check` exits non-zero when any output is stale (used in CI).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from catalog_lib import (  # noqa: E402
    CATALOG_DIR, DOCS_DIR, NOTES_DIR, ROOT, load_catalog, load_triage, note_code, note_files, parse_note,
)

TYPE_ORDER = ["Keynote", "Breakout", "Theater", "Lightning Talk", "Table Talk", "Lab", "Digital Lab",
              "Pre-recorded", "Broadcast Stage", "Innovation Session"]
PROGRESS = {  # key: (emoji, label)
    "done": ("✅", "완료"), "review": ("🔍", "검토 중"), "draft": ("✍️", "작성 중"),
    "pick": ("📌", "정리 대상"), "hold": ("⏸️", "보류"), "skip": ("➖", "제외"), "todo": ("·", "미검토"),
}


def group_of(s: dict) -> str:
    """Nav/index group: keynotes stand alone, everything else by its first catalog topic."""
    return "Keynote" if s["type"] == "Keynote" else (s["topics"] or ["Other"])[0]


def cell(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def collect():
    sessions = load_catalog()
    by_code = {s["code"]: s for s in sessions}
    triage = load_triage()
    notes = {}
    for path in note_files():
        code = note_code(path, by_code)
        if code:
            fm, _ = parse_note(path)
            notes[code] = {"path": path, "fm": fm}
    for s in sessions:
        n = notes.get(s["code"])
        t = triage.get(s["code"], {})
        if n and n["fm"].get("status") in ("draft", "review", "done"):
            s["progress"] = n["fm"]["status"]
        else:
            s["progress"] = t.get("status") if t.get("status") in ("pick", "hold", "skip") else "todo"
        s["triage_note"] = t.get("note", "") or ""
        s["note_path"] = n["path"] if n else None
        s["note_fm"] = n["fm"] if n else {}
    return sessions


def media(s: dict) -> str:
    parts = []
    if s["video"]:
        parts.append(f"[▶]({s['video']})")
    if s["slides"]:
        parts.append(f"[🖼]({s['slides']})")
    if s["transcript"]:
        parts.append("📝")
    return " ".join(parts)


def sessions_md(sessions: list[dict]) -> str:
    groups = defaultdict(list)
    for s in sessions:
        groups[s["type"] or "(none)"].append(s)
    order = [t for t in TYPE_ORDER if t in groups] + sorted(t for t in groups if t not in TYPE_ORDER)
    progress = Counter(s["progress"] for s in sessions)
    meta = json.loads((CATALOG_DIR / "meta.json").read_text())

    out = [
        "# Microsoft Ignite 2026 — 전체 세션 목록",
        "",
        "<!-- generated by tools/build_pages.py — 직접 수정하지 말 것. 트리아지는 catalog/triage.yml 에서 -->",
        "",
        f"공식 세션 카탈로그(`{meta['source']}`) 스냅샷 · 수집 {meta['fetched_at']} · "
        f"**{meta['sessions']}개 세션** (반복 회차 포함 {meta['raw_instances']}개 인스턴스)",
        "",
        "진행: " + " · ".join(f"{PROGRESS[k][0]} {PROGRESS[k][1]} {progress.get(k, 0)}" for k in PROGRESS),
        "",
        "미디어: ▶ 온디맨드 영상 · 🖼 슬라이드 · 📝 트랜스크립트 (`tools/fetch_sources.py <CODE>` 로 받기)",
        "",
        "| 세션 타입 | 개수 |",
        "|---|---:|",
        *[f"| [{t}](#{re.sub(r'[^a-z0-9]+', '-', t.lower()).strip('-')}) | {len(groups[t])} |" for t in order],
        "",
    ]
    for t in order:
        out += [f"## {t}", "", "| 진행 | Code | Title | Topic | Level | Tags | Media |", "|:-:|---|---|---|:-:|---|---|"]
        for s in groups[t]:
            title = cell(s["title"])
            if s["note_path"]:
                title = f"[{title}](../{s['note_path'].relative_to(ROOT).as_posix()})"
            tags = ", ".join(s["tags"][:4]) + (" …" if len(s["tags"]) > 4 else "")
            out.append(
                f"| {PROGRESS[s['progress']][0]} | [{s['code']}]({s['url']}) | {title} | {cell(', '.join(s['topics']))} "
                f"| {s['level'] or ''} | {cell(tags)} | {media(s)} |"
            )
        out.append("")
    return "\n".join(out)


def explorer_json(sessions: list[dict]) -> str:
    rows = []
    for s in sessions:
        rows.append({
            "c": s["code"], "t": s["title"], "y": s["type"], "p": s["topics"], "g": s["tags"],
            "l": s["level"], "s": s["speakers"], "d": s["duration_min"],
            "at": s["slots"][0]["start"] if s["slots"] else "", "u": s["url"], "v": s["video"],
            "k": s["slides"], "tr": bool(s["transcript"]), "x": s["description"], "pr": s["progress"],
            "n": f"sessions/{s['note_path'].stem}/" if s["note_path"] else "",
        })
    return json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + "\n"


def notes_index(sessions: list[dict]) -> str:
    written = [s for s in sessions if s["note_path"]]
    out = [
        "---", "title: 세션 노트", "hide:", "  - toc", "---", "",
        "<!-- generated by tools/build_pages.py — 직접 수정하지 말 것 -->", "",
        '<div class="dg-page-heading" markdown="1">', "",
        '<p class="dg-eyebrow">SESSION NOTES</p>', "", "# 세션 노트", "",
        f"Ignite 2026 세션 {len(sessions)}개 중 **{len(written)}개** 정리됨. "
        "전체 목록과 필터는 [세션 카탈로그](../catalog/index.md)에서.", "", "</div>", "",
    ]
    if not written:
        out += ["아직 작성된 노트가 없습니다. [기여 가이드](../contributing.md)를 참고해 첫 노트를 추가하세요.", ""]
        return "\n".join(out)
    groups = defaultdict(list)
    for s in written:
        groups[group_of(s)].append(s)
    for topic in sorted(groups, key=lambda g: (g != "Keynote", g)):
        out += [f"## {topic}", "", "| Code | Title | Type | 상태 | Updated |", "|---|---|---|:-:|---|"]
        for s in sorted(groups[topic], key=lambda x: x["code"]):
            emoji, label = PROGRESS[s["progress"]]
            out.append(f"| `{s['code']}` | [{cell(s['title'])}]({s['note_path'].name}) | {s['type']} "
                       f"| {emoji} {label} | {s['note_fm'].get('last_updated', '')} |")
        out.append("")
    return "\n".join(out)


def home_blocks(sessions: list[dict], text: str) -> str:
    written = [s for s in sessions if s["note_path"]]
    done = sum(1 for s in written if s["progress"] == "done")
    types = Counter(s["type"] for s in sessions)
    stats = "\n".join([
        '<div class="dg-stats" markdown="0">',
        f'<div class="dg-stat"><strong>{len(sessions):,}</strong><span>sessions</span></div>',
        f'<div class="dg-stat"><strong>{len(types)}</strong><span>session types</span></div>',
        f'<div class="dg-stat"><strong>{sum(1 for s in sessions if s["video"]):,}</strong><span>on-demand videos</span></div>',
        f'<div class="dg-stat"><strong>{sum(1 for s in sessions if s["progress"] == "pick")}</strong><span>picked</span></div>',
        f'<div class="dg-stat"><strong>{len(written)}<small>/{done}</small></strong><span>notes / done</span></div>',
        "</div>",
    ])
    recent = sorted(written, key=lambda s: (str(s["note_fm"].get("last_updated", "")), s["code"]), reverse=True)[:6]
    if recent:
        cards = ['<div class="dg-note-grid" markdown="0">']
        for s in recent:
            emoji, label = PROGRESS[s["progress"]]
            cards.append(
                f'<a class="dg-note-card dg-note-card--{s["progress"]}" href="sessions/{s["note_path"].stem}/">'
                f'<span class="dg-note-meta"><code>{s["code"]}</code><span>{s["type"]}</span><span>{emoji} {label}</span></span>'
                f'<strong>{s["title"]}</strong><span class="dg-note-topics">{" · ".join(s["topics"][:3])}</span></a>'
            )
        cards.append("</div>")
        recent_md = "\n".join(cards)
    else:
        recent_md = '<p class="dg-empty">아직 작성된 노트가 없습니다 — <a href="catalog/">카탈로그</a>에서 정리할 세션을 고르세요.</p>'

    def put(name: str, body: str, src: str) -> str:
        pattern = re.compile(rf"(<!-- gen:{name} -->\n).*?(<!-- /gen:{name} -->)", re.S)
        if not pattern.search(src):
            raise SystemExit(f"docs/index.md is missing <!-- gen:{name} --> markers")
        return pattern.sub(lambda m: m.group(1) + body + "\n" + m.group(2), src)

    return put("recent", recent_md, put("stats", stats, text))


def mkdocs_nav(sessions: list[dict], text: str) -> str:
    written = [s for s in sessions if s["note_path"]]
    themes = sorted(p for p in (DOCS_DIR / "themes").glob("*.md") if not p.name.startswith(("_", "index")))
    lines = [
        "# gen:nav — generated by tools/build_pages.py (keynotes, then sessions by first catalog topic)",
        "nav:",
        "  - 홈: index.md",
        "  - 세션 카탈로그: catalog/index.md",
        "  - 세션 노트:",
        "      - sessions/index.md",
    ]
    groups = defaultdict(list)
    for s in written:
        groups[group_of(s)].append(s)
    for topic in sorted(groups, key=lambda g: (g != "Keynote", g)):
        lines.append(f"      - {json.dumps(topic, ensure_ascii=False)}:")
        for s in sorted(groups[topic], key=lambda x: x["code"]):
            label = json.dumps(f"{s['code']} — {s['title']}", ensure_ascii=False)
            lines.append(f"          - {label}: sessions/{s['note_path'].name}")
    lines += ["  - 테마:", "      - themes/index.md"]
    lines += [f"      - themes/{p.name}" for p in themes]
    lines += ["  - 기여하기: contributing.md", "# /gen:nav"]
    pattern = re.compile(r"# gen:nav.*?# /gen:nav", re.S)
    if not pattern.search(text):
        raise SystemExit("mkdocs.yml is missing the '# gen:nav' ... '# /gen:nav' block")
    return pattern.sub(lambda _: "\n".join(lines), text)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()

    sessions = collect()
    home = DOCS_DIR / "index.md"
    mkdocs_yml = ROOT / "mkdocs.yml"
    outputs = {
        CATALOG_DIR / "SESSIONS.md": sessions_md(sessions),
        DOCS_DIR / "catalog" / "sessions.json": explorer_json(sessions),
        NOTES_DIR / "index.md": notes_index(sessions),
        home: home_blocks(sessions, home.read_text(encoding="utf-8")),
        mkdocs_yml: mkdocs_nav(sessions, mkdocs_yml.read_text(encoding="utf-8")),
    }
    stale = [p for p, body in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != body]
    if args.check:
        if stale:
            print("stale generated files (run `python tools/build_pages.py`):", *[f"  {p.relative_to(ROOT)}" for p in stale], sep="\n")
            raise SystemExit(1)
        print("generated files are up to date")
        return
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(outputs[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
